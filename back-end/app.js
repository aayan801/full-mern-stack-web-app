require('dotenv').config({ silent: true }) // load environmental variables from a hidden file named .env
const express = require('express') // CommonJS import style!
const morgan = require('morgan') // middleware for nice logging of incoming HTTP requests
const cors = require('cors') // middleware for enabling CORS (Cross-Origin Resource Sharing) requests.
const mongoose = require('mongoose')
const path = require('path')

const app = express() // instantiate an Express object
app.use(morgan('dev', { skip: (req, res) => process.env.NODE_ENV === 'test' })) // log all incoming requests, except when in unit test mode.  morgan has a few logging default styles - dev is a nice concise color-coded style
app.use(cors()) // allow cross-origin resource sharing

// use express's builtin body-parser middleware to parse any data included in a request
app.use(express.json()) // decode JSON-formatted incoming POST data
app.use(express.urlencoded({ extended: true })) // decode url-encoded incoming POST data

// serve static files (like images) from the public folder
app.use('/static', express.static(path.join(__dirname, 'public')))

// connect to database
mongoose
  .connect(`${process.env.DB_CONNECTION_STRING}`)
  .then(data => console.log(`Connected to MongoDB`))
  .catch(err => console.error(`Failed to connect to MongoDB: ${err}`))

// load the dataabase models we want to deal with
const { Message } = require('./models/Message')
const { User } = require('./models/User')

// a route to handle fetching all messages
app.get('/messages', async (req, res) => {
  // load all messages from database
  try {
    const messages = await Message.find({})
    res.json({
      messages: messages,
      status: 'all good',
    })
  } catch (err) {
    console.error(err)
    res.status(400).json({
      error: err,
      status: 'failed to retrieve messages from the database',
    })
  }
})

// a route to handle fetching a single message by its id
app.get('/messages/:messageId', async (req, res) => {
  // load all messages from database
  try {
    const messages = await Message.find({ _id: req.params.messageId })
    res.json({
      messages: messages,
      status: 'all good',
    })
  } catch (err) {
    console.error(err)
    res.status(400).json({
      error: err,
      status: 'failed to retrieve messages from the database',
    })
  }
})
// a route to handle logging out users
app.post('/messages/save', async (req, res) => {
  // try to save the message to the database
  try {
    const message = await Message.create({
      name: req.body.name,
      message: req.body.message,
    })
    return res.json({
      message: message, // return the message we just saved
      status: 'all good',
    })
  } catch (err) {
    console.error(err)
    return res.status(400).json({
      error: err,
      status: 'failed to save the message to the database',
    })
  }
})

// a route to send the About Us page content as JSON
app.get('/aboutus', (req, res) => {
  res.json({
    name: 'Aayan',
    paragraphs: [
      "Hi, I'm Aayan, a student based in Abu Dhabi. I'm interested in machine learning and software engineering, and I enjoy building things that sit somewhere between research and real products.",
      "Outside of coursework, I'm working on a quantum machine learning research project under a professor's supervision, focused on quantum generative models for anomaly detection. This semester I'm also taking Deep Learning and Causal Inference, and working with teammates on CurbCut, a mobile web app for our software engineering class.",
      "When I'm not coding or reading papers, I like to play football, watch movies, and try new food spots. This page is part of a MERN stack exercise: the text and photo you see here are served as JSON from an Express back-end and rendered by React.",
    ],
    imageUrl: `${req.protocol}://${req.get('host')}/static/me.jpg`,
    status: 'all good',
  })
})

// export the express app we created to make it available to other modules
module.exports = app // CommonJS export style!